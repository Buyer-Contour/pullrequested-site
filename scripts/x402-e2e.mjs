import assert from 'node:assert/strict';
import { x402Client } from '@x402/core/client';
import { decodePaymentRequiredHeader, decodePaymentResponseHeader, encodePaymentSignatureHeader } from '@x402/core/http';
import { ExactEvmScheme } from '@x402/evm/exact/client';
import { createPublicClient, erc20Abi, http, parseEventLogs } from 'viem';
import { privateKeyToAccount } from 'viem/accounts';
import { baseSepolia as chain } from 'viem/chains';
import { makeQuote } from '../lib/payments/quotes.mjs';
import { baseSepolia, x402Path } from '../lib/payments/x402.mjs';

const walletKey = process.env.X402_TEST_PAYER_PRIVATE_KEY;
assert.ok(/^0x[a-fA-F0-9]{64}$/.test(walletKey), 'Set X402_TEST_PAYER_PRIVATE_KEY from a test wallet Bot secret');
const payTo = process.env.X402_PAY_TO?.toLowerCase();
assert.ok(/^0x[a-f0-9]{40}$/.test(payTo), 'Set X402_PAY_TO to the expected recipient');
const payer = privateKeyToAccount(walletKey);
assert.notEqual(payer.address.toLowerCase(), payTo, 'Use separate sender and recipient wallets');
const { quote, token } = makeQuote({ amount_cents: 50, description: 'Base Sepolia x402 verification' }, process.env.QUOTE_SIGNING_SECRET);
const url = new URL(`${x402Path}?quote=${token}`, process.env.PAYMENTS_ORIGIN);
const rpc = createPublicClient({ chain, transport: http(process.env.X402_TEST_RPC_URL) });
const challenge = await fetch(url, { redirect: 'error' });
assert.equal(challenge.status, 402);
const paymentRequired = decodePaymentRequiredHeader(challenge.headers.get('Payment-Required'));
const [accepted, ...other] = paymentRequired.accepts;
assert.equal(other.length, 0);
assert.equal(accepted?.scheme, 'exact');
assert.equal(accepted?.network, baseSepolia);
const asset = '0x036CbD53842c5426634e7929541eC2318f3dCF7e';
assert.equal(accepted.asset.toLowerCase(), asset.toLowerCase());
assert.equal(accepted.amount, '500000');
assert.equal(accepted.payTo.toLowerCase(), payTo);
const balance = await rpc.readContract({ address: asset, abi: erc20Abi, functionName: 'balanceOf', args: [payer.address] });
assert.ok(balance >= 500000n, 'The test payer needs at least 0.50 Base Sepolia USDC');
const client = new x402Client().register(baseSepolia, new ExactEvmScheme(payer));
const proof = encodePaymentSignatureHeader(await client.createPaymentPayload(paymentRequired));
const options = { headers: { 'Payment-Signature': proof }, redirect: 'error' };
const settled = await fetch(url, options);
assert.equal(settled.status, 200);
const receipt = await settled.json();
const paymentResponse = decodePaymentResponseHeader(settled.headers.get('Payment-Response'));
assert.equal(paymentResponse.success, true);
assert.equal(paymentResponse.network, baseSepolia);
assert.equal(receipt.quote_id, quote.id);
assert.equal(receipt.payment_id, paymentResponse.transaction);
const onChain = await rpc.getTransactionReceipt({ hash: paymentResponse.transaction });
assert.equal(onChain.status, 'success');
const transfers = parseEventLogs({ abi: erc20Abi, eventName: 'Transfer', logs: onChain.logs });
assert.ok(transfers.some(({ address, args }) => address.toLowerCase() === asset.toLowerCase() &&
  args.from.toLowerCase() === payer.address.toLowerCase() && args.to.toLowerCase() === payTo && args.value === 500000n));
const replay = await fetch(url, options);
assert.equal(replay.status, 409);
assert.equal((await replay.json()).error, 'payment_replayed');
console.log(`Base Sepolia: 0.50 USDC settled in ${paymentResponse.transaction}; replay rejected (HTTP 409).`);
